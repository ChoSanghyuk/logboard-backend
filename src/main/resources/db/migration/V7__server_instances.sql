-- Multi-instance servers (spec/multi-instance-server/design.md §3).
-- A server has 1-20 instances; host, port, log path, login and host-key pin move from servers to server_instances.
-- (server_id, host, ssh_port, log_path) uniqueness among active instances is checked by the app (no index: an update
-- may swap or re-add values, and Hibernate flushes inserts before deletes).

CREATE TABLE server_instances (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_id            BIGINT        NOT NULL REFERENCES servers (id) ON DELETE CASCADE,
    position             INTEGER       NOT NULL CHECK (position >= 0),  -- user order (display, anchor tie-break)
    host                 VARCHAR(255)  NOT NULL,
    ssh_port             INTEGER       NOT NULL DEFAULT 22 CHECK (ssh_port BETWEEN 1 AND 65535),
    log_path             VARCHAR(1024) NOT NULL,
    username             VARCHAR(100)  NOT NULL,
    auth_type            VARCHAR(16)   NOT NULL CHECK (auth_type IN ('PASSWORD', 'KEY')),
    secret_enc           TEXT,                           -- AES-GCM ciphertext of password or private key
    host_key_fingerprint VARCHAR(128),                   -- TOFU pin, per host:port
    deleted_at           TIMESTAMPTZ,                    -- soft delete when error logs reference the instance
    created_at           TIMESTAMPTZ   NOT NULL,
    updated_at           TIMESTAMPTZ   NOT NULL
);
CREATE INDEX server_instances_server_id_idx ON server_instances (server_id);

-- Every existing server becomes one instance (position 0).
INSERT INTO server_instances (server_id, position, host, ssh_port, log_path, username, auth_type, secret_enc,
                              host_key_fingerprint, deleted_at, created_at, updated_at)
SELECT id, 0, host, ssh_port, log_path, username, auth_type, secret_enc, host_key_fingerprint, deleted_at,
       created_at, updated_at
FROM servers;

-- instance_id: instance of the current anchor/crop. raw_files: {"<instanceId>": {"path", "totalLines"}} (one raw copy
-- per fetched instance). fetch_failures: [{instanceId, host, sshPort, logPath, message}].
ALTER TABLE error_logs
    ADD COLUMN instance_id    BIGINT REFERENCES server_instances (id),
    ADD COLUMN raw_files      TEXT,
    ADD COLUMN fetch_failures TEXT NOT NULL DEFAULT '[]';

UPDATE error_logs e SET instance_id = i.id FROM server_instances i WHERE i.server_id = e.server_id;

UPDATE error_logs SET
    raw_files = json_build_object(instance_id::text,
                                  json_build_object('path', raw_file_path, 'totalLines', total_lines))::text,
    candidates = (SELECT COALESCE(jsonb_agg(c || jsonb_build_object('instanceId', instance_id) ORDER BY n), '[]'::jsonb)
                  FROM jsonb_array_elements(candidates::jsonb) WITH ORDINALITY AS t(c, n))::text;

ALTER TABLE error_logs
    ALTER COLUMN instance_id SET NOT NULL,
    ALTER COLUMN raw_files SET NOT NULL,
    ALTER COLUMN fetch_failures DROP DEFAULT;
CREATE INDEX error_logs_instance_id_idx ON error_logs (instance_id);

ALTER TABLE servers
    DROP COLUMN host,
    DROP COLUMN ssh_port,
    DROP COLUMN log_path,
    DROP COLUMN username,
    DROP COLUMN auth_type,
    DROP COLUMN secret_enc,
    DROP COLUMN host_key_fingerprint;
