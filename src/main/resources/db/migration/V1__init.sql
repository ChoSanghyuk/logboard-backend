-- Logboard MVP initial schema (design.md §5).
-- Enum-like columns are VARCHAR + CHECK so they map to JPA @Enumerated(STRING).

CREATE TABLE servers (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100)  NOT NULL UNIQUE,  -- used in storage paths and MCP serverName filter
    host             VARCHAR(255)  NOT NULL,
    ssh_port         INTEGER       NOT NULL DEFAULT 22 CHECK (ssh_port BETWEEN 1 AND 65535),
    username         VARCHAR(100)  NOT NULL,
    auth_type        VARCHAR(16)   NOT NULL CHECK (auth_type IN ('PASSWORD', 'KEY')),
    secret_enc       TEXT,                           -- AES-GCM ciphertext of password or private key
    log_path         VARCHAR(1024) NOT NULL,
    rotated_pattern  VARCHAR(1024),
    log_pattern_key  VARCHAR(64),                    -- preset key, e.g. SPRING_BOOT_3
    custom_log_regex TEXT,                           -- custom regex with named groups ts, level
    timezone         VARCHAR(64)   NOT NULL DEFAULT 'Asia/Seoul',
    charset          VARCHAR(32)   NOT NULL DEFAULT 'UTF-8',
    created_at       TIMESTAMPTZ   NOT NULL,
    updated_at       TIMESTAMPTZ   NOT NULL,
    CONSTRAINT servers_one_log_pattern CHECK ((log_pattern_key IS NULL) <> (custom_log_regex IS NULL))
);

CREATE TABLE llm_endpoints (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL UNIQUE,
    base_url    VARCHAR(1024) NOT NULL,
    model       VARCHAR(255)  NOT NULL,
    api_key_enc TEXT,
    timeout_sec INTEGER       NOT NULL DEFAULT 120 CHECK (timeout_sec > 0),
    is_default  BOOLEAN       NOT NULL DEFAULT FALSE
);
-- At most one default endpoint.
CREATE UNIQUE INDEX llm_endpoints_single_default ON llm_endpoints (is_default) WHERE is_default;

CREATE TABLE prompt_templates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL UNIQUE,
    content    TEXT         NOT NULL,                -- must contain {{errorLog}} (validated in app)
    is_default BOOLEAN      NOT NULL DEFAULT FALSE
);
-- At most one default template.
CREATE UNIQUE INDEX prompt_templates_single_default ON prompt_templates (is_default) WHERE is_default;

CREATE TABLE error_logs (
    id                VARCHAR(16)   PRIMARY KEY CHECK (id ~ '^[0-9]{8}-[0-9]{3,}$'),  -- YYYYMMDD-NNN
    server_id         BIGINT        NOT NULL REFERENCES servers (id),
    requested_time    TIMESTAMPTZ   NOT NULL,
    window_min        INTEGER       NOT NULL CHECK (window_min > 0),
    raw_file_path     VARCHAR(1024) NOT NULL,
    crop_start_line   INTEGER       NOT NULL,
    crop_end_line     INTEGER       NOT NULL,
    anchor_line       INTEGER       NOT NULL,
    exception_class   VARCHAR(512),                  -- null when the candidate is an ERROR entry without a trace
    exception_message TEXT,
    status            VARCHAR(16)   NOT NULL CHECK (status IN
                          ('CROPPED', 'CONFIRMED', 'ANALYZED', 'TERMINATED', 'DEV_REQUIRED', 'DISCARDED')),
    note              TEXT,
    resolved_by       VARCHAR(8)    CHECK (resolved_by IN ('USER', 'AGENT')),
    resolution        TEXT,
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT error_logs_crop_range CHECK (crop_start_line <= anchor_line AND anchor_line <= crop_end_line)
);
CREATE INDEX error_logs_status_idx ON error_logs (status);
CREATE INDEX error_logs_server_id_idx ON error_logs (server_id);
CREATE INDEX error_logs_created_at_idx ON error_logs (created_at);

-- Daily counter for error log IDs; the row is locked with SELECT ... FOR UPDATE.
CREATE TABLE error_log_seq (
    seq_date DATE    PRIMARY KEY,
    last_seq INTEGER NOT NULL
);

CREATE TABLE analyses (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    error_log_id       VARCHAR(16) NOT NULL REFERENCES error_logs (id),
    llm_endpoint_id    BIGINT      NOT NULL REFERENCES llm_endpoints (id),
    prompt_template_id BIGINT      NOT NULL REFERENCES prompt_templates (id),
    rendered_prompt    TEXT        NOT NULL,
    reply              TEXT,
    status             VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    error_message      TEXT,
    created_at         TIMESTAMPTZ NOT NULL,
    finished_at        TIMESTAMPTZ
);
CREATE INDEX analyses_error_log_id_idx ON analyses (error_log_id, created_at DESC);
